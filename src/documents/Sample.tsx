import { Doc, H, P } from '../reader/Reader';

export default function Sample() {
  return (
    <Doc title="サンプル文書">
      <H>このアプリについて</H>
      <P>
        このアプリは、文章を一行ずつ読むためのものです。
        「。」が来るたびに、一行として区切られます。
        今読んでいる行だけが、黄色く光ります。
      </P>

      <H>操作のしかた</H>
      <P>
        右矢印キーを押すと、次の行に進みます。
        左矢印キーを押すと、前の行に戻ります。
        行をクリックすると、その行に移動できます。
      </P>

      <H>文章の書き方</H>
      <P>
        文章は src/documents フォルダに置きます。
        段落は P タグで、見出しは H タグで囲みます。
        かぎかっこの中の「。」では区切りません。
        たとえば、彼は「わかった。ありがとう。」と言った。
        この文は一行として扱われます。
      </P>
    </Doc>
  );
}
